/**
 * Renders a miniature phone wallpaper (390×844 layout, 240 px wide) of every pattern for the mobile app's pattern picker,
 * through the same renderer page the app uses (run `pnpm mobile:renderer` first).
 *
 *   pnpm mobile:thumbs [--engine webkit]
 */
import { Buffer } from 'node:buffer'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium, webkit } from 'playwright'
import templates from '../src/lib/templates'
import { DEFAULT_EFFECTS, buildFrame } from '../src/lib/effects'
import { defaultVariables } from '../src/lib/pattern'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outDir = path.join(root, 'mobile/assets/thumbs')
const engine = process.argv.includes('webkit') ? webkit : chromium
const source = fs.readFileSync(path.join(root, 'mobile/src/renderer/html.ts'), 'utf8')
const html = JSON.parse(source.slice(source.indexOf('"'), source.lastIndexOf('"') + 1)) as string

const browser = await engine.launch()
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
// Stands in for the app's WebView bridge, collecting the page's replies.
const bridge = '<script>window.replies=[];window.ReactNativeWebView={postMessage:m=>replies.push(JSON.parse(m))}</script>'
await page.setContent(html.replace('<head>', `<head>${bridge}`))
await page.waitForFunction(() => (window as any).replies.some((r: any) => r.ready))

fs.rmSync(outDir, { recursive: true, force: true })
fs.mkdirSync(outDir, { recursive: true })
const slugs = Object.keys(templates)
let failed = 0
for (const [i, slug] of slugs.entries()) {
  const t = templates[slug]
  const frame = buildFrame({ template: t.template, variables: t.variables, values: defaultVariables(t.variables), effects: DEFAULT_EFFECTS, animate: false })
  const reply = await page.evaluate(async ({ frame, id }) => {
    const w = window as any
    w.stylixir.exportImage(id, { width: 390, height: 844, format: 'webp', quality: 0.8, pixelRatio: 240 / 390, slug: '', frame })
    for (;;) {
      const r = w.replies.find((m: any) => m.id === id)
      if (r)
        return r
      await new Promise(resolve => setTimeout(resolve, 10))
    }
  }, { frame, id: i })
  if (reply.error) {
    failed++
    console.error(slug, reply.error)
    continue
  }
  fs.writeFileSync(path.join(outDir, `${slug}.webp`), Buffer.from(reply.data, 'base64'))
}
await browser.close()

const map = slugs.map(slug => `  '${slug}': require('../assets/thumbs/${slug}.webp'),`).join('\n')
fs.writeFileSync(path.join(root, 'mobile/src/thumbs.ts'), `// Generated by \`pnpm mobile:thumbs\`; do not edit.\nexport const thumbs: Record<string, number> = {\n${map}\n}\n`)
const kb = fs.readdirSync(outDir).reduce((sum, f) => sum + fs.statSync(path.join(outDir, f)).size, 0) / 1024
console.log(`${slugs.length - failed}/${slugs.length} thumbnails, ${Math.round(kb)} KB`)
process.exit(failed ? 1 : 0)
