/**
 * Bundles src/renderer into one HTML page for the mobile app's pattern view.
 *
 *   pnpm mobile:renderer
 *
 * Rerun after changing the engine (src/lib) so the app paints and exports the same way the site does.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'vite'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const result = await build({
  configFile: false,
  root,
  logLevel: 'warn',
  resolve: { alias: { '~/': `${root}/src/` } },
  build: {
    write: false,
    lib: { entry: 'src/renderer/main.ts', formats: ['iife'], name: 'stylixirRenderer', fileName: 'renderer' },
    rollupOptions: { output: { inlineDynamicImports: true } },
  },
})
const output = (Array.isArray(result) ? result[0] : result) as { output: { code?: string }[] }
const js = output.output[0].code ?? ''

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html,body{margin:0;height:100%;overflow:hidden;background:#000}#root{position:fixed;inset:0;isolation:isolate;overflow:hidden;container-type:size}</style>
<style id="frame-css"></style></head><body><div id="root"></div><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`

const target = path.join(root, 'mobile/src/renderer/html.ts')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, `// Generated by \`pnpm mobile:renderer\` from src/renderer; do not edit.\nexport default ${JSON.stringify(html)}\n`)
console.log(`wrote ${path.relative(root, target)} (${Math.round(html.length / 1024)} KB)`)
